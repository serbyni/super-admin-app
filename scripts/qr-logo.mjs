// Embeds the brand mark shown in the middle of QR codes into src/lib/qr/logo.ts (data URL), so
// downloaded SVG/PNG QR codes are self-contained. Run again after changing the logo:
//   node scripts/qr-logo.mjs
import { readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const root = join(import.meta.dirname, "..");
const SOURCE = "public/brand/serbi-email-mark.png";
const png = readFileSync(join(root, SOURCE));
const out = `// GENERATED by scripts/qr-logo.mjs from ${SOURCE} — do not edit by hand.
/** Brand mark placed in the middle of QR codes (PNG data URL, ${png.length} bytes). */
export const QR_LOGO = "data:image/png;base64,${png.toString("base64")}";
`;
writeFileSync(join(root, "src/lib/qr/logo.ts"), out);
console.log(`src/lib/qr/logo.ts written (${png.length} bytes from ${SOURCE})`);
