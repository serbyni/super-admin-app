// Generates Tailwind tonal palettes (50–950) from the Serbi brand seed colors
// using Material Color Utilities. Output: src/styles/palettes.css
// Run: npm run tokens:palettes
import { writeFileSync } from "node:fs";
import { argbFromHex, hexFromArgb, TonalPalette, Hct } from "@material/material-color-utilities";

// Tailwind step -> Material tone (lightness 0–100)
const STEPS = {
  50: 95,
  100: 90,
  200: 80,
  300: 70,
  400: 60,
  500: 50,
  600: 40,
  700: 30,
  800: 20,
  900: 10,
  950: 5,
};

const seeds = {
  coffee: "#6F4E37", // primary brand (espresso brown)
  latte: "#6D5B4F", // secondary (warm neutral brown)
  slate: "#24434B", // tertiary (deep teal, admin actions)
  sand: "#82746D", // neutral-variant (outlines, muted text)
  orange: "#E67E22", // CTA accent (order / place order)
  sage: "#5B8C5A", // success / available
  sky: "#2F6FDB", // info / pending / links in dashboards
  red: "#BA1A1A", // error
};

let css = `/* AUTO-GENERATED by scripts/generate-palettes.mjs — do not edit by hand. */\n@theme {\n`;
for (const [name, hex] of Object.entries(seeds)) {
  const hct = Hct.fromInt(argbFromHex(hex));
  const palette = TonalPalette.fromHueAndChroma(hct.hue, hct.chroma);
  for (const [step, tone] of Object.entries(STEPS)) {
    css += `  --color-${name}-${step}: ${hexFromArgb(palette.tone(tone))};\n`;
  }
}
css += `}\n`;
writeFileSync(new URL("../src/styles/palettes.css", import.meta.url), css);
console.log("Wrote src/styles/palettes.css");
